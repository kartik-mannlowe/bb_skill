test("7+8: changed files are kept by default; --force removes only files the installer created", () => {
  const { h, ap, install: inst } = setup(["claude"]);
  try {
    const replaced = path.join(ap.claudeDir, "commands", "bb.md");
    write(replaced, "my original");
    inst();
    const created = path.join(ap.claudeDir, "commands", "bb-find.md");
    fs.writeFileSync(created, "I edited Brewboard's command");
    fs.writeFileSync(replaced, "I edited it after Brewboard replaced mine");
    let res = uninstallNow(h);
    assert.strictEqual(res.code, 2);
    assert.deepStrictEqual(res.plan.keep.map((k) => k.path).sort(), [replaced, created].sort());
    assert.ok(fs.existsSync(created) && fs.existsSync(replaced));
    assert.ok(fs.existsSync(tracking.trackingFile(h.paths)), "kept items stay recorded");
    res = uninstallNow(h, { force: true });
    assert.ok(!fs.existsSync(created), "created by the installer: removed with --force");
    assert.strictEqual(fs.readFileSync(replaced, "utf8"), "I edited it after Brewboard replaced mine", "never forced");
    assert.ok(fs.existsSync(tracking.originalPathFor(h.paths, replaced)), "the user's original stays in the backup");
  } finally { h.cleanup(); }
});

test("4+5: the installer's own sign-in config is removed; a replaced config is restored; others are kept", async () => {
  const srv = await mockServer();
  try {
    // created by the installer's sign-in
    let { h, install: inst } = setup(["claude"]);
    try {
      inst();
      await signIn(h, srv);
      assert.strictEqual(tracking.readTracking(h.paths).config.created, true);
      const out = sink();
      const code = await main(["uninstall", "--yes"], { env: h.env, stdin: new PassThrough(), stdout: out, stderr: sink() });
      assert.strictEqual(code, 0, out.text());
      assert.ok(!fs.existsSync(h.paths.configFile));
      assert.match(out.text(), /Your saved Brewboard credentials will be deleted/);
      assert.match(out.text(), /only deleted locally/);
    } finally { h.cleanup(); }

    // an earlier config of the user's, replaced by the installer's sign-in
    ({ h, install: inst } = setup(["claude"]));
    try {
      inst();
      const earlier = JSON.stringify({ url: "https://other.example.com", api_key: "k", api_secret: "s", my_setting: 1 });
      write(h.paths.configFile, earlier, 0o600);
      await signIn(h, srv);
      const t = tracking.readTracking(h.paths);
      assert.strictEqual(t.config.created, false);
      assert.strictEqual(fs.statSync(t.config.original).mode & 0o777, 0o600);
      const { code } = uninstallNow(h);
      assert.strictEqual(code, 0);
      assert.strictEqual(fs.readFileSync(h.paths.configFile, "utf8"), earlier, "earlier config restored exactly");
      assert.strictEqual(fs.statSync(h.paths.configFile).mode & 0o777, 0o600);
    } finally { h.cleanup(); }

    // created some other way (bb.py init): untouched
    ({ h, install: inst } = setup(["claude"]));
    try {
      inst();
      write(h.paths.configFile, '{"url":"x"}', 0o600);
      const { plan, code } = uninstallNow(h);
      assert.strictEqual(plan.config.action, "keep");
      assert.strictEqual(fs.readFileSync(h.paths.configFile, "utf8"), '{"url":"x"}');
      assert.strictEqual(code, 0);
    } finally { h.cleanup(); }

    // installer-created but changed afterwards: kept, unless --force
    ({ h, install: inst } = setup(["claude"]));
    try {
      inst();
      await signIn(h, srv);
      fs.appendFileSync(h.paths.configFile, " ");
      let res = uninstallNow(h);
      assert.strictEqual(res.plan.config.action, "keep");
      assert.ok(fs.existsSync(h.paths.configFile));
      assert.strictEqual(res.code, 0); // the config is not part of the "kept files" count
      res = uninstallNow(h, { force: true });
      assert.ok(!fs.existsSync(h.paths.configFile));
    } finally { h.cleanup(); }
  } finally { await srv.close(); }
});

