test("14: the packed npm entry point accepts both `uninstall` and `--uninstall`", () => {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "bbnpx-pack-"));
  try {
    const pack = spawnSync("npm", ["pack", "--pack-destination", work, "--silent"], { cwd: path.join(__dirname, ".."), encoding: "utf8" });
    assert.strictEqual(pack.status, 0, pack.stderr);
    const tgz = path.join(work, pack.stdout.trim().split("\n").pop());
    for (const form of [["uninstall"], ["--uninstall"]]) {
      const { h, install: inst } = setup(["claude"]);
      try {
        inst();
        const env = { ...h.env, PATH: `${path.dirname(process.execPath)}:${h.env.PATH}`, npm_config_cache: path.join(work, "cache") };
        const r = spawnSync("npx", ["--yes", `--package=${tgz}`, "brewboard-skill", ...form, "--yes"], { cwd: h.home, env, encoding: "utf8" });
        assert.strictEqual(r.status, 0, r.stdout + r.stderr);
        assert.match(r.stdout, /Brewboard is uninstalled\./);
        assert.ok(!fs.existsSync(h.paths.skillDir));
      } finally { h.cleanup(); }
    }
  } finally { fs.rmSync(work, { recursive: true, force: true }); }
});
